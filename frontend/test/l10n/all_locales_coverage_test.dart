void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('message list is not empty', () {
    expect(_messages, isNotEmpty);
  });

  for (final Locale locale in AppLocalizations.supportedLocales) {
    test('every message resolves to a non-empty string for "$locale"', () {
      final AppLocalizations l = lookupAppLocalizations(locale);
      expect(l.localeName, locale.toString());
      final List<String> empty = <String>[];
      _messages.forEach((String key, _Message read) {
        final Object value = read(l);
        expect(value, isA<String>(), reason: key);
        if ((value as String).isEmpty) empty.add(key);
      });
      expect(empty, isEmpty, reason: 'empty messages in $locale');
    });
  }

  test('non-English locales translate at least some messages', () {
    final AppLocalizations en = lookupAppLocalizations(const Locale('en'));
    for (final Locale locale in AppLocalizations.supportedLocales) {
      if (locale.languageCode == 'en') continue;
      final AppLocalizations l = lookupAppLocalizations(locale);
      final int differing =
          _messages.values.where((_Message read) => read(l) != read(en)).length;
      expect(differing, greaterThan(0), reason: '$locale');
    }
  });
}
