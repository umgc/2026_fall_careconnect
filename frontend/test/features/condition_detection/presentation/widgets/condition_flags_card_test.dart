// Validates the post-call condition screening card and its JSON model: every per-model status
// (in progress, complete, skipped, failed), the mandatory disclaimer, and the load-error state.
// The card is pure presentation over a parsed model, so no HTTP or providers are needed; real
// localization delegates are used so the English ARB copy is what gets asserted.
import 'package:care_connect_app/features/condition_detection/models/condition_flags.dart';
import 'package:care_connect_app/features/condition_detection/presentation/widgets/condition_flags_card.dart';
import 'package:care_connect_app/l10n/app_localizations.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

const _disclaimer =
    'This is a screening flag generated by an AI model. It is not a clinical diagnosis. '
    'Consult a healthcare professional for clinical evaluation.';

Future<void> _pumpCard(WidgetTester tester, ConditionFlagsResult? result) async {
  await tester.pumpWidget(
    MaterialApp(
      localizationsDelegates: AppLocalizations.localizationsDelegates,
      supportedLocales: AppLocalizations.supportedLocales,
      home: Scaffold(
        body: SingleChildScrollView(child: ConditionFlagsCard(result: result)),
      ),
    ),
  );
  await tester.pump();
}

/// Builds a result through `fromJson` so the parsing path is exercised by every card test.
ConditionFlagsResult _result(List<Map<String, dynamic>> runs) =>
    ConditionFlagsResult.fromJson({'disclaimer': _disclaimer, 'runs': runs});

Map<String, dynamic> _run(String modelId, String status,
        {String? skipReason, List<Map<String, dynamic>> flags = const []}) =>
    {
      'modelId': modelId,
      'displayName': 'Server name for $modelId',
      'inputKind': 'PATIENT_AUDIO',
      'status': status,
      'skipReason': skipReason,
      'completedAt': status == 'COMPLETE' ? '2026-10-07T21:00:00Z' : null,
      'flags': flags,
    };

void main() {
  group('ConditionFlagsResult.fromJson', () {
    /// Lower-case values from the wire are normalized; a missing status defaults to PENDING.
    test('normalizes case and defaults missing fields', () {
      final result = ConditionFlagsResult.fromJson({
        'disclaimer': 'd',
        'runs': [
          {
            'modelId': 'm',
            'flags': [
              {'condition': 'ptsd', 'severityLevel': 2.0, 'severityLabel': 'moderate'},
            ],
          },
        ],
      });

      final run = result.runs.single;
      expect(run.status, 'PENDING');
      expect(run.isInProgress, isTrue);
      expect(run.flags.single.condition, 'PTSD');
      expect(run.flags.single.severityLevel, 2);
      expect(run.flags.single.severityLabel, 'MODERATE');
    });

    /// A malformed body (runs not a list) yields an empty, non-crashing result.
    test('tolerates a malformed runs field', () {
      expect(ConditionFlagsResult.fromJson({'runs': 'oops'}).runs, isEmpty);
    });
  });

  group('ConditionFlagsCard', () {
    /// The disclaimer must appear on every surface showing flags, whatever the state.
    testWidgets('always shows the mandatory disclaimer', (tester) async {
      await _pumpCard(tester, _result([_run(ConditionFlagsCard.voiceModelId, 'PENDING')]));

      expect(find.text('Condition screening'), findsOneWidget);
      expect(find.text(_disclaimer), findsOneWidget);
    });

    /// A failed request (null result) tells the user to refresh instead of showing nothing.
    testWidgets('shows a load error when the request failed', (tester) async {
      await _pumpCard(tester, null);

      expect(find.text("Couldn't load condition screening. Pull down to refresh."), findsOneWidget);
      expect(find.text(_disclaimer), findsOneWidget);
    });

    /// PENDING and PROCESSING both read as "analyzing" with a spinner and a refresh hint.
    testWidgets('shows a processing state for in-progress models', (tester) async {
      await _pumpCard(tester, _result([
        _run(ConditionFlagsCard.voiceModelId, 'PENDING'),
        _run(ConditionFlagsCard.transcriptModelId, 'PROCESSING'),
      ]));

      expect(find.text('Voice analysis'), findsOneWidget);
      expect(find.text('Transcript analysis'), findsOneWidget);
      expect(find.byType(CircularProgressIndicator), findsNWidgets(2));
      expect(
        find.text('Analyzing the call. This can take several minutes — pull down to refresh.'),
        findsNWidgets(2),
      );
    });

    /// Completed runs list each condition with a localized severity and the evidence summary;
    /// level 0 reads "No indicator" so it is not mistaken for a flag.
    testWidgets('renders completed flags with localized names', (tester) async {
      // Arrange — one voice run (DAM bands) and one transcript run (with evidence).
      await _pumpCard(tester, _result([
        _run(ConditionFlagsCard.voiceModelId, 'COMPLETE', flags: [
          {'condition': 'DEPRESSION', 'severityLevel': 1, 'severityLabel': 'MILD_TO_MODERATE'},
          {'condition': 'ANXIETY', 'severityLevel': 0, 'severityLabel': 'NONE'},
        ]),
        _run(ConditionFlagsCard.transcriptModelId, 'COMPLETE', flags: [
          {
            'condition': 'PTSD',
            'severityLevel': 3,
            'severityLabel': 'HIGH',
            'evidenceSummary': 'Describes recurring nightmares.',
          },
          {'condition': 'BIPOLAR', 'severityLevel': 0, 'severityLabel': 'NONE'},
        ]),
      ]));

      // Assert
      expect(find.text('Depression'), findsOneWidget);
      expect(find.text('Mild to moderate'), findsOneWidget);
      expect(find.text('Anxiety'), findsOneWidget);
      expect(find.text('No indicator'), findsNWidgets(2));
      expect(find.text('PTSD'), findsOneWidget);
      expect(find.text('High'), findsOneWidget);
      expect(find.text('Bipolar disorder'), findsOneWidget);
      expect(find.text('Describes recurring nightmares.'), findsOneWidget);
      expect(find.bySemanticsLabel('PTSD: High. Describes recurring nightmares.'), findsOneWidget);
      expect(find.bySemanticsLabel('Anxiety: No indicator'), findsOneWidget);
      expect(find.byType(CircularProgressIndicator), findsNothing);
    });

    /// Each skip reason the backend can send has its own plain-language sentence.
    testWidgets('explains every skip reason', (tester) async {
      const reasons = {
        'CALL_TOO_SHORT': 'Not analyzed because the call was shorter than 30 seconds.',
        'NO_RECORDING': "Not analyzed because the call wasn't recorded.",
        'NO_PATIENT_AUDIO': 'Not analyzed because no audio from the patient was captured.',
        'INSUFFICIENT_SPEECH': 'Not analyzed because the patient spoke for less than 30 seconds.',
        'AUDIO_EXPIRED':
            'Not analyzed because the call audio expired before it could be processed.',
        'TRANSCRIPT_UNAVAILABLE': 'Not analyzed because no transcript is available for this call.',
        'TRANSCRIPT_TIMEOUT':
            'Not analyzed because the transcript took too long to become available.',
        'PATIENT_SPEAKER_UNIDENTIFIED':
            "Not analyzed because the transcript couldn't tell which lines the patient said.",
        'MODEL_UNAVAILABLE': "Not analyzed because the screening model isn't available.",
        'SOMETHING_NEW': 'Not analyzed.',
      };
      for (final entry in reasons.entries) {
        await _pumpCard(tester, _result([
          _run(ConditionFlagsCard.voiceModelId, 'SKIPPED', skipReason: entry.key),
        ]));
        expect(find.text(entry.value), findsOneWidget, reason: entry.key);
      }
    });

    /// A permanently failed run says so rather than spinning forever.
    testWidgets('shows a failure message for failed models', (tester) async {
      await _pumpCard(tester, _result([_run(ConditionFlagsCard.voiceModelId, 'FAILED')]));

      expect(find.text('Analysis failed after several attempts.'), findsOneWidget);
    });

    /// A model the app does not know yet falls back to the server's display name.
    testWidgets('falls back to the server display name for unknown models', (tester) async {
      await _pumpCard(tester, _result([_run('future-model', 'PENDING')]));

      expect(find.text('Server name for future-model'), findsOneWidget);
    });
  });
}
